const onLangCallbacks = [];

export function onLanguageChange(fn) {
  onLangCallbacks.push(fn);
}

export function applyLanguage(lang) {
  appState.currentLang = lang;
  localStorage.setItem('payagent_lang', lang);

  if (lang === 'tr') {
    if (el.btnLangTr) el.btnLangTr.classList.add('active');
    if (el.btnLangEn) el.btnLangEn.classList.remove('active');
  } else {
    if (el.btnLangEn) el.btnLangEn.classList.add('active');
    if (el.btnLangTr) el.btnLangTr.classList.remove('active');
  }

  // Translate static data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.getAttribute('data-i18n');
    if (i18n[lang] && i18n[lang][key]) {
      node.textContent = i18n[lang][key];
    }
  });

  // Notify dependent UI modules (fleet, audit, etc.)
  onLangCallbacks.forEach((cb) => {
    try { cb(lang); } catch (e) { console.error('Language callback error:', e); }
  });
}

export function initI18n() {
  if (el.btnLangTr) el.btnLangTr.addEventListener('click', () => applyLanguage('tr'));
  if (el.btnLangEn) el.btnLangEn.addEventListener('click', () => applyLanguage('en'));
}
